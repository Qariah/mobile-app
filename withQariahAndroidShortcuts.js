/**
 * Expo config plugin: the three Android app shortcuts (a long press on the
 * app icon): Continue listening, Continue reading and Search. iOS has the same
 * three as App Shortcuts (plugins/app-shortcuts/BayaanAppShortcuts.swift).
 * Approved proposal: https://claude.ai/artifact/BBg2cj1gbVhppCLoLronFM
 *
 * Each static shortcut opens the link `<scheme>://<route>` in the main
 * activity, so the link routes app/continue-listening.tsx,
 * app/continue-reading.tsx and app/search.tsx run
 * (services/shortcuts/appShortcuts.ts).
 *
 * On every prebuild it writes, under android/app/src/main/res:
 *   xml/qariah_shortcuts.xml            the shortcuts
 *   values/qariah_shortcuts.xml         the English labels
 *   drawable/qariah_shortcut_*.xml      the icons (Material Icons, Apache 2.0)
 * and adds the `android.app.shortcuts` meta-data to the launcher activity.
 *
 * It also adds a block to MainActivity.onCreate (tag
 * `qariah-shortcut-history`). When Android kills the process and the user
 * opens the app from Recents, the activity starts again with its first
 * intent, flagged FLAG_ACTIVITY_LAUNCHED_FROM_HISTORY. React Native 0.88's
 * getInitialURL no longer checks that flag, so a shortcut link would run a
 * second time: Continue listening would start the audio by itself (test case
 * SC-12). The block drops the link of a shortcut from such an intent.
 *
 * The labels are English. The Arabic comes from the review pack, not by hand
 * (TECH_DEBT row 305); it will go in values-ar through
 * scripts/native-strings-from-review.mjs.
 */
