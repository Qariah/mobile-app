const labelName = (s, kind) => `qariah_shortcut_${s.id}_${kind}`;

/** The app's link scheme: the first `scheme` entry (withBayaanWidgets reads it too). */
function appScheme(config) {
  const scheme = Array.isArray(config.scheme)
    ? config.scheme[0]
    : config.scheme;
  if (!scheme) throw new Error('[withQariahAndroidShortcuts] no app scheme');
  return scheme;
}

function renderShortcutsXml({packageName, scheme}) {
  const items = SHORTCUTS.map(s =>
    [
      '  <shortcut',
      `    android:shortcutId="${s.id}"`,
      '    android:enabled="true"',
      `    android:icon="@drawable/${s.icon}"`,
      `    android:shortcutShortLabel="@string/${labelName(s, 'short')}"`,
      `    android:shortcutLongLabel="@string/${labelName(s, 'long')}">`,
      '    <intent',
      '      android:action="android.intent.action.VIEW"',
      `      android:targetPackage="${packageName}"`,
      `      android:targetClass="${packageName}.MainActivity"`,
      `      android:data="${scheme}://${s.route}"/>`,
      '  </shortcut>',
    ].join('\n'),
  );
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- ${MARKER} -->`,
    '<shortcuts xmlns:android="http://schemas.android.com/apk/res/android">',
    ...items,
    '</shortcuts>',
    '',
  ].join('\n');
}

function renderLabelsXml() {
  const lines = SHORTCUTS.flatMap(s => [
    `  <string name="${labelName(s, 'short')}">${s.short}</string>`,
    `  <string name="${labelName(s, 'long')}">${s.long}</string>`,
  ]);
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- ${MARKER} -->`,
    '<resources>',
    ...lines,
    '</resources>',
    '',
  ].join('\n');
}

function renderIconXml(s) {
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- ${MARKER} -->`,
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
    '  android:width="24dp"',
    '  android:height="24dp"',
    '  android:viewportWidth="24"',
    '  android:viewportHeight="24">',
    `  <path android:fillColor="${ICON_COLOR}" android:pathData="${s.path}"/>`,
    '</vector>',
    '',
  ].join('\n');
}

/** Every file the plugin writes, relative to res/. */
function renderResources({packageName, scheme}) {
  const files = {
    [path.join('xml', `${SHORTCUTS_XML}.xml`)]: renderShortcutsXml({
      packageName,
      scheme,
    }),
    [path.join('values', 'qariah_shortcuts.xml')]: renderLabelsXml(),
  };
  for (const s of SHORTCUTS) {
    files[path.join('drawable', `${s.icon}.xml`)] = renderIconXml(s);
  }
  return files;
}

function writeResources(resDir, options) {
  for (const [rel, text] of Object.entries(renderResources(options))) {
    const file = path.join(resDir, rel);
    fs.mkdirSync(path.dirname(file), {recursive: true});
    fs.writeFileSync(file, text);
  }
}

const isLauncher = activity =>
  (activity['intent-filter'] || []).some(f =>
    (f.category || []).some(
      c => c.$['android:name'] === 'android.intent.category.LAUNCHER',
    ),
  );

/** Adds the shortcuts meta-data to the launcher activity, once. */
function addShortcutsMetaData(manifest) {
  const app = manifest.manifest.application?.[0];
  const activity = (app?.activity || []).find(isLauncher);
  if (!activity) {
    throw new Error('[withQariahAndroidShortcuts] no launcher activity');
  }
  activity['meta-data'] = (activity['meta-data'] || []).filter(
    m => m.$['android:name'] !== 'android.app.shortcuts',
  );
  activity['meta-data'].push({
    $: {
      'android:name': 'android.app.shortcuts',
      'android:resource': `@xml/${SHORTCUTS_XML}`,
    },
  });
  return manifest;
}

/** The MainActivity block: drop a shortcut link from a launch from Recents. */
function historyGuardSource(scheme) {
  const routes = SHORTCUTS.map(s => `"${s.route}"`).join(', ');
  return [
    '    // Qariah: a launch from Recents after process death repeats the first',
    '    // intent. A shortcut link must not run again (withQariahAndroidShortcuts.js).',
    '    if ((intent.flags and android.content.Intent.FLAG_ACTIVITY_LAUNCHED_FROM_HISTORY) != 0 &&',
    `        intent.data?.scheme == "${scheme}" &&`,
    `        setOf(${routes}).contains(intent.data?.host)) {`,
    '      intent.data = null',
    '    }',
  ].join('\n');
}

/** MainActivity.kt with the history guard before super.onCreate. */
function addHistoryGuard(contents, scheme) {
  return mergeContents({
    src: contents,
    comment: '    //',
    tag: 'qariah-shortcut-history',
    offset: 0,
    anchor: /super\.onCreate\(null\)/,
    newSrc: historyGuardSource(scheme),
  }).contents;
}

function withQariahAndroidShortcuts(config) {
  config = withMainActivity(config, cfg => {
    if (cfg.modResults.language !== 'kt') {
      throw new Error(
        '[withQariahAndroidShortcuts] MainActivity must be Kotlin',
      );
    }
    cfg.modResults.contents = addHistoryGuard(
      cfg.modResults.contents,
      appScheme(cfg),
    );
    return cfg;
  });
  config = withAndroidManifest(config, cfg => {
    cfg.modResults = addShortcutsMetaData(cfg.modResults);
    return cfg;
  });
  return withDangerousMod(config, [
    'android',
    async cfg => {
      writeResources(
        path.join(
          cfg.modRequest.platformProjectRoot,
          'app',
          'src',
          'main',
          'res',
        ),
        {packageName: cfg.android.package, scheme: appScheme(cfg)},
      );
      return cfg;
    },
  ]);
}

