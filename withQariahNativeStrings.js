/**
 * Expo config plugin: the widget-picker text of the bayaan-widgets library in
 * other languages, as Android app resources.
 *
 * i18n/native/widget-strings.json maps a language to string resources, for
 * example {"ar": {"bayaan_widget_ayah_label": "آية اليوم"}}.
 * scripts/native-strings-from-review.mjs writes it from the Arabic review
 * pack. On every prebuild this plugin writes
 * android/app/src/main/res/values-<lang>/bayaan_widgets.xml. An app resource
 * replaces the library resource of the same name and language (RFC-021
 * seam), so the upstream module stays as it is.
 *
 * Why not Expo's `locales` (app.config.ts), which writes app_name: the app
 * module has no default (values/) text for most of these names, because the
 * library holds it. Android lint reads one module at a time, and its
 * ExtraTranslation check (fatal in lintVitalRelease) calls a translation
 * without a default in the same module an error. Expo cannot add the
 * tools:ignore attribute; this file does.
 *
 * iOS needs no plugin: the widget text is in
 * targets/widgets/_shared/Localizable.xcstrings.
 */
const fs = require('fs');
const path = require('path');
const {withDangerousMod} = require('expo/config-plugins');

const SOURCE = path.join('i18n', 'native', 'widget-strings.json');
const FILE_NAME = 'bayaan_widgets.xml';
const MARKER = 'Generated by withQariahNativeStrings.js';
// An Android language qualifier: "ar", or "pt-rBR".
const LANGUAGE = /^[a-z]{2,3}(-r[A-Z]{2})?$/;
const RESOURCE_NAME = /^[a-z][a-z0-9_]*$/;

/** Text for an Android <string> (the same escaping as withBayaanWidgets). */
function escapeXml(value) {
  const escaped = value
    .replace(/\\/g, '\\\\')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"');
  // A leading @ or ? would make Android read the string as a reference.
  return /^[@?]/.test(escaped) ? `\\${escaped}` : escaped;
}

/** One language's resource file. */
function renderWidgetStrings(strings) {
  const lines = Object.entries(strings).map(([name, value]) => {
    if (!RESOURCE_NAME.test(name) || typeof value !== 'string' || !value) {
      throw new Error(
        `[withQariahNativeStrings] ${SOURCE}: bad string ${JSON.stringify(
          name,
        )}`,
      );
    }
    return `  <string name="${name}">${escapeXml(value)}</string>`;
  });
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- ${MARKER} from ${SOURCE} (scripts/native-strings-from-review.mjs). Do not edit. -->`,
    '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="ExtraTranslation">',
    ...lines,
    '</resources>',
    '',
  ].join('\n');
}

/**
 * Writes values-<lang>/bayaan_widgets.xml for each language in `byLanguage`,
 * and removes the files this plugin wrote for a language that is gone.
 * values/bayaan_widgets.xml (plugins/withBayaanWidgets.js) has no marker,
 * so it is never touched.
 */
function writeWidgetStrings(resDir, byLanguage) {
  for (const language of Object.keys(byLanguage)) {
    if (!LANGUAGE.test(language)) {
      throw new Error(
        `[withQariahNativeStrings] ${SOURCE}: "${language}" is not an Android language qualifier`,
      );
    }
  }
  if (fs.existsSync(resDir)) {
    for (const dir of fs.readdirSync(resDir)) {
      if (!dir.startsWith('values-')) continue;
      const file = path.join(resDir, dir, FILE_NAME);
      if (!fs.existsSync(file)) continue;
      if (!fs.readFileSync(file, 'utf8').includes(MARKER)) continue;
      if (!(dir.slice('values-'.length) in byLanguage)) fs.rmSync(file);
    }
  }
  for (const [language, strings] of Object.entries(byLanguage)) {
    const dir = path.join(resDir, `values-${language}`);
    fs.mkdirSync(dir, {recursive: true});
    fs.writeFileSync(path.join(dir, FILE_NAME), renderWidgetStrings(strings));
  }
}

function withQariahNativeStrings(config) {
  return withDangerousMod(config, [
    'android',
    async cfg => {
      const source = path.join(cfg.modRequest.projectRoot, SOURCE);
      const byLanguage = JSON.parse(fs.readFileSync(source, 'utf8'));
      writeWidgetStrings(
        path.join(
          cfg.modRequest.platformProjectRoot,
          'app',
          'src',
          'main',
          'res',
        ),
        byLanguage,
      );
      return cfg;
    },
  ]);
}

module.exports = withQariahNativeStrings;
module.exports.renderWidgetStrings = renderWidgetStrings;
module.exports.writeWidgetStrings = writeWidgetStrings;
