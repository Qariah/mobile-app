// @ai
//
// scripts/lib/widget-fonts.mjs
// ----------------------------
// Qariah (Sprint 51): check that a build holds the fonts of the Home Screen
// widgets.
//
// The widget fonts are copies. scripts/sync-widget-fonts.js copies them from
// data/ and assets/ into targets/widgets/ (the iOS widget extension) and into
// modules/bayaan-widgets/android/src/main/assets/fonts/ (Android). Git ignores
// the copies. Before Sprint 51 only `npm run prebuild` made them, so the
// release builds 3490 and 3506 shipped with no Quran font in the widgets.
//
// This module reads a finished build and lists each widget font that it lacks:
//   - an Android APK    (assets/fonts/<font>)
//   - an Android AAB    (base/assets/fonts/<font>)
//   - an iOS .xcarchive (the widget .appex holds <font> at its root)
// It reads the file list of a zip itself (no `unzip` tool), so the tests run
// on any machine with no build.
//
// A build that has no widget module is not checked. A release line from before
// the widgets (for example hotfix/3.2.0-anr-splash) has no widget assets, so
// the check skips it, unless the caller asks for the widgets (`requireWidgets`).
// The archive scripts ask when their own source tree holds the widget module.
//
// Which fonts each platform must hold: only the fonts that the widget code
// loads. Sprint 51 reading of the code:
//   - Android: ArabicBitmap.kt loads DigitalKhattFont.otf (Quran text) and
//     ScheherazadeNew-Regular.ttf (dhikr text). No Kotlin file loads
//     surah_names.ttf, so an Android build does not need it.
//   - iOS: WidgetChrome.swift loads "DigitalKhattNewMadinaRegular" (the Quran
//     font), "ScheherazadeNew-Regular" and "icomoon". The font family of
//     surah_names.ttf is "icomoon" ("Font generated by IcoMoon"), and the
//     lock screen accessory draws the surah name glyph with it
//     (WidgetFonts.surahGlyph). So iOS needs all three files.

import {
  closeSync,
  existsSync,
  openSync,
  readSync,
  readdirSync,
  statSync,
} from 'node:fs';
import path from 'node:path';
import {Buffer} from 'node:buffer';

/** The fonts that the Android widget code loads (ArabicBitmap.kt). */
export const ANDROID_FONT_FILES = Object.freeze([
  'DigitalKhattFont.otf',
  'ScheherazadeNew-Regular.ttf',
]);

/** The fonts that the iOS widget loads: the files of UIAppFonts in targets/widgets/Info.plist. */
export const IOS_FONT_FILES = Object.freeze([
  'DigitalKhattFont.otf',
  'surah_names.ttf',
  'ScheherazadeNew-Regular.ttf',
]);

/** Where the widget module puts its own assets in an Android build. */
const WIDGET_ASSET_PREFIX = Object.freeze({
  aab: 'base/assets/widgets/',
  apk: 'assets/widgets/',
});

/** A folder of the source tree that holds the widget module, for each kind of build. */
const WIDGET_SOURCE_DIR = Object.freeze({
  aab: path.join('modules', 'bayaan-widgets', 'android'),
  apk: path.join('modules', 'bayaan-widgets', 'android'),
  xcarchive: path.join('targets', 'widgets'),
});

/** The widget extension of the iOS app (`name` in targets/widgets/expo-target.config.js). */
export const WIDGET_APPEX = 'BayaanWidgetsExtension.appex';

const SIG_EOCD = 0x06054b50;
const SIG_ZIP64_LOCATOR = 0x07064b50;
const SIG_ZIP64_EOCD = 0x06064b50;
const SIG_CENTRAL = 0x02014b50;
const EOCD_SIZE = 22;
const MAX_COMMENT = 0xffff;
const ZIP64_LOCATOR_SIZE = 20;

function readAt(fd, length, position) {
  const buffer = Buffer.alloc(length);
  let done = 0;
  while (done < length) {
    const count = readSync(fd, buffer, done, length - done, position + done);
    if (count === 0) throw new Error('the file ended early');
    done += count;
  }
  return buffer;
}

function readBig(buffer, offset) {
  return Number(buffer.readBigUInt64LE(offset));
}

/** Find where the central directory is: its first byte, its size, its entry count. */
function locateCentralDirectory(fd, fileSize) {
  const tailLength = Math.min(fileSize, EOCD_SIZE + MAX_COMMENT);
  const tailStart = fileSize - tailLength;
  const tail = readAt(fd, tailLength, tailStart);
  let eocd = -1;
  for (let i = tailLength - EOCD_SIZE; i >= 0; i -= 1) {
    if (tail.readUInt32LE(i) === SIG_EOCD) {
      eocd = i;
      break;
    }
  }
  if (eocd < 0) throw new Error('this is not a zip file');
  let count = tail.readUInt16LE(eocd + 10);
  let size = tail.readUInt32LE(eocd + 12);
  let offset = tail.readUInt32LE(eocd + 16);
  const needsZip64 =
    count === 0xffff || size === 0xffffffff || offset === 0xffffffff;
  if (needsZip64) {
    const locator = eocd - ZIP64_LOCATOR_SIZE;
    if (locator < 0 || tail.readUInt32LE(locator) !== SIG_ZIP64_LOCATOR) {
      throw new Error('the zip64 end record is missing');
    }
    const record = readAt(fd, 56, readBig(tail, locator + 8));
    if (record.readUInt32LE(0) !== SIG_ZIP64_EOCD) {
      throw new Error('the zip64 end record is not valid');
    }
    count = readBig(record, 32);
    size = readBig(record, 40);
    offset = readBig(record, 48);
  }
  return {count, size, offset};
}

/** The uncompressed size from the zip64 extra field of an entry, when the header holds 0xffffffff. */
function zip64Size(extra) {
  let at = 0;
  while (at + 4 <= extra.length) {
    const id = extra.readUInt16LE(at);
    const length = extra.readUInt16LE(at + 2);
    if (id === 0x0001 && length >= 8) return readBig(extra, at + 4);
    at += 4 + length;
  }
  throw new Error('the zip64 extra field is missing');
}

/**
 * The entries of a zip file, from its central directory: [{name, size}], where
 * size is the uncompressed size in bytes. Reads no entry data.
 */
export function listZipEntries(file) {
  const fd = openSync(file, 'r');
  try {
    const fileSize = statSync(file).size;
    const {count, size, offset} = locateCentralDirectory(fd, fileSize);
    const directory = readAt(fd, size, offset);
    const entries = [];
    let at = 0;
    for (let i = 0; i < count; i += 1) {
      if (
        at + 46 > directory.length ||
        directory.readUInt32LE(at) !== SIG_CENTRAL
      ) {
        throw new Error('the zip central directory is not valid');
      }
      let entrySize = directory.readUInt32LE(at + 24);
      const nameLength = directory.readUInt16LE(at + 28);
      const extraLength = directory.readUInt16LE(at + 30);
      const commentLength = directory.readUInt16LE(at + 32);
      const name = directory.toString('utf8', at + 46, at + 46 + nameLength);
      if (entrySize === 0xffffffff) {
        const extraStart = at + 46 + nameLength;
        entrySize = zip64Size(
          directory.subarray(extraStart, extraStart + extraLength),
        );
      }
      entries.push({name, size: entrySize});
      at += 46 + nameLength + extraLength + commentLength;
    }
    return entries;
  } finally {
    closeSync(fd);
  }
}

/** Which kind of build a path names: 'apk', 'aab' or 'xcarchive'. Throws on any other name. */
export function artifactKind(file) {
  const ext = path.extname(file.replace(/\/+$/, '')).toLowerCase();
  if (ext === '.apk') return 'apk';
  if (ext === '.aab') return 'aab';
  if (ext === '.xcarchive') return 'xcarchive';
  throw new Error(`${file}: expected an .apk, an .aab or an .xcarchive`);
}

/** Split the expected fonts into the missing ones and the empty ones. */
function classify(expected, sizeOf) {
  const missing = [];
  const empty = [];
  for (const font of expected) {
    const size = sizeOf(font);
    if (size === undefined) missing.push(font);
    else if (size === 0) empty.push(font);
  }
  return {missing, empty};
}

function checkZip(file, kind) {
  const prefix = kind === 'aab' ? 'base/assets/fonts/' : 'assets/fonts/';
  const entries = listZipEntries(file);
  const sizes = new Map(entries.map(entry => [entry.name, entry.size]));
  const {missing, empty} = classify(ANDROID_FONT_FILES, font =>
    sizes.get(prefix + font),
  );
  return {
    where: prefix,
    widgetMarker: WIDGET_ASSET_PREFIX[kind],
    hasWidgets: entries.some(entry =>
      entry.name.startsWith(WIDGET_ASSET_PREFIX[kind]),
    ),
    expected: ANDROID_FONT_FILES,
    missing,
    empty,
  };
}

/** The widget extensions of an .xcarchive: Products/Applications/<app>.app/PlugIns/<widget>.appex */
function findWidgetAppexes(archive) {
  const applications = path.join(archive, 'Products', 'Applications');
  let apps;
  try {
    apps = readdirSync(applications).filter(name => name.endsWith('.app'));
  } catch {
    throw new Error(
      `${archive}: no Products/Applications folder (not an archive?)`,
    );
  }
  const found = [];
  for (const app of apps) {
    const appex = path.join(applications, app, 'PlugIns', WIDGET_APPEX);
    try {
      if (statSync(appex).isDirectory()) found.push(appex);
    } catch {
      // This app has no widget extension.
    }
  }
  return found;
}

function checkArchive(archive) {
  const appexes = findWidgetAppexes(archive);
  if (appexes.length === 0) {
    return {
      where: `PlugIns/${WIDGET_APPEX}`,
      widgetMarker: `PlugIns/${WIDGET_APPEX}`,
      hasWidgets: false,
      expected: IOS_FONT_FILES,
      missing: [],
      empty: [],
    };
  }
  // One app is the normal case. With more, a font must be in every widget.
  const missing = new Set();
  const empty = new Set();
  for (const appex of appexes) {
    const result = classify(IOS_FONT_FILES, font => {
      try {
        return statSync(path.join(appex, font)).size;
      } catch {
        return undefined;
      }
    });
    result.missing.forEach(font => missing.add(font));
    result.empty.forEach(font => empty.add(font));
  }
  return {
    where: `PlugIns/${WIDGET_APPEX}`,
    widgetMarker: `PlugIns/${WIDGET_APPEX}`,
    hasWidgets: true,
    expected: IOS_FONT_FILES,
    missing: IOS_FONT_FILES.filter(font => missing.has(font)),
    empty: IOS_FONT_FILES.filter(font => empty.has(font)),
  };
}

/**
 * True when the source tree at `root` holds the widget module that `kind` of
 * build needs: modules/bayaan-widgets/android (Android) or targets/widgets (iOS).
 */
export function treeHasWidgets(kind, root) {
  return existsSync(path.join(root, WIDGET_SOURCE_DIR[kind]));
}

/**
 * Check one build. Returns {file, kind, ok, skipped, where, expected, missing,
 * empty, hasWidgets, note}.
 *
 * A build without the widget module (no widget assets: `hasWidgets` is false) is
 * skipped: `ok` is true and `skipped` is true. With `requireWidgets` it fails
 * instead, because the caller knows that its source tree holds the module.
 * Otherwise `ok` is true when every font that the platform needs is present and
 * not empty. Throws when the file is not a build of a known kind or cannot be read.
 */
export function checkWidgetFonts(file, {requireWidgets = false} = {}) {
  const kind = artifactKind(file);
  const result =
    kind === 'xcarchive' ? checkArchive(file) : checkZip(file, kind);
  if (!result.hasWidgets) {
    const note = `the build has no widget module (no ${result.widgetMarker})`;
    return {
      file,
      kind,
      ...result,
      ok: !requireWidgets,
      skipped: !requireWidgets,
      note: requireWidgets
        ? `${note}, but the source tree holds the widget module`
        : `${note}; the fonts are not checked`,
    };
  }
  const ok = result.missing.length === 0 && result.empty.length === 0;
  return {file, kind, ...result, ok, skipped: false, note: ''};
}

/** The lines to print for one result. */
export function describeResult(result) {
  const name = path.basename(result.file.replace(/\/+$/, ''));
  if (result.skipped) {
    return [`skip  ${name}: ${result.note}`];
  }
  if (result.ok) {
    return [
      `ok    ${name}: ${result.expected.length} widget fonts in ${result.where}`,
    ];
  }
  const lines = [`FAIL  ${name}: the widget fonts are not in the build`];
  if (result.note) lines.push(`      ${result.note}`);
  if (result.missing.length > 0) {
    lines.push(
      `      missing in ${result.where}: ${result.missing.join(', ')}`,
    );
  }
  if (result.empty.length > 0) {
    lines.push(`      empty in ${result.where}: ${result.empty.join(', ')}`);
  }
  return lines;
}

