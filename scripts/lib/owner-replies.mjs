// @ai
//
// scripts/lib/owner-replies.mjs
// -----------------------------
// Omar's replies to the daily triage, kept where the next run reads them.
//
// WHY. Each run of the cloud routine is a new session that reads only
// `qariah-main` and GitHub. A reply that Omar typed in a run's session stayed
// in that session, so the next run asked the same question again (he said
// "share fixed" on 2026-10-08 and again on 2026-10-11). A run cannot commit,
// so a reply goes on the card issue (`Daily card`) as a comment:
//
//   owner-reply: <Omar's words>
//
// A run posts it when Omar replies in its session (scripts/owner-reply.mjs
// post), or Omar posts it himself (the GitHub app works). Every run reads them
// first (scripts/owner-reply.mjs list). scripts/owner-actions.mjs also applies
// the `effect` of a reply phrase (docs/operations/owner-actions.json →
// replies), so a NEEDS YOU line stops without a pull request.
//
// Only a comment by the repository owner counts. A reply is data for the
// report and for owner-actions. It never allows a write that the routine's
// hard rules forbid.

export const PREFIX = 'owner-reply:';

// The cloud GitHub proxy appends this footer to a comment that a session
// posts. It is not part of the reply.
const FOOTER = /\n+-{3,}\s*\n+_Generated by [^\n]*_\s*$/;

/** The login of the repository owner, from `owner/repo`. */
export const ownerOf = repo => String(repo || '').split('/')[0];

/**
 * The owner's replies among issue comments (GitHub REST shape), oldest first.
 * A reply is a comment by `owner` whose first non-empty line starts with
 * `owner-reply:` (any case).
 * → [{date: 'YYYY-MM-DD', at, text, url}]
 */
export function parseOwnerReplies(comments, {owner}) {
  const out = [];
  for (const c of comments || []) {
    const login = (c.user && c.user.login) || c.author || '';
    if (!owner || login.toLowerCase() !== String(owner).toLowerCase()) continue;
    const body = String(c.body || '')
      .replace(FOOTER, '')
      .trim();
    if (!body.toLowerCase().startsWith(PREFIX)) continue;
    const text = body.slice(PREFIX.length).trim().slice(0, 2000);
    if (!text) continue;
    const at = c.created_at || c.createdAt || '';
    out.push({date: at.slice(0, 10), at, text, url: c.html_url || c.url || ''});
  }
  return out.sort((a, b) => (a.at < b.at ? -1 : a.at > b.at ? 1 : 0));
}

/** Lower case, no quotes, single spaces: the form a phrase is matched in. */
export const normalize = s =>
  String(s || '')
    .toLowerCase()
    .replace(/[‘’“”"'`]/g, '')
    .replace(/\s+/g, ' ')
    .trim();

/**
 * The reply phrase (owner-actions.json → replies[]) that a reply text starts
 * with, or null. The phrase must end at a word boundary: "phase 2 yes" matches
 * "phase 2 yes, go ahead" but not "phase 2 yesterday".
 */
export function matchPhrase(text, replies) {
  const t = normalize(String(text || '').split('\n')[0]);
  for (const r of replies || []) {
    const p = normalize(r.phrase);
    if (!p) continue;
    if (t === p) return r;
    if (t.startsWith(p) && /^[^a-z0-9]/.test(t.slice(p.length))) return r;
  }
  return null;
}

// The item fields a reply effect may set: the fields that a session may also
// write by hand (owner-actions.json → _comment). `statusDate` comes from the
// reply's own date.
export const EFFECT_FIELDS = ['status', 'answer'];

/**
 * The owner-actions list with the reply effects applied, oldest reply first,
 * so a newer reply wins. A reply sets `statusDate` to its own date. It does
 * not change an item that is closed (`closedOn`), or an item whose hand-set
 * `statusDate` is newer than the reply.
 * → {list, applied: [{phrase, item, date}]}
 */
export function applyOwnerReplies(list, replies) {
  const copy = JSON.parse(JSON.stringify(list || {items: []}));
  const applied = [];
  for (const reply of replies || []) {
    const r = matchPhrase(reply.text, copy.replies);
    if (!r || !r.effect) continue;
    const item = (copy.items || []).find(i => i.id === r.item);
    if (!item || item.closedOn) continue;
    if (item.statusDate && item.statusDate > reply.date) continue;
    for (const k of EFFECT_FIELDS) if (k in r.effect) item[k] = r.effect[k];
    item.statusDate = reply.date;
    applied.push({phrase: r.phrase, item: item.id, date: reply.date});
  }
  return {list: copy, applied};
}

/** One printable line for a reply: the date, the text, and what it matched. */
export function replyLine(reply, replies) {
  const r = matchPhrase(reply.text, replies);
  const text = reply.text.replace(/\s+/g, ' ');
  const shown = text.length > 160 ? `${text.slice(0, 157)}...` : text;
  const tag = r
    ? r.effect
      ? ` [phrase "${r.phrase}" → ${r.item}: applied]`
      : ` [phrase "${r.phrase}" → ${r.item}: a session must act]`
    : '';
  return `${reply.date} · ${shown}${tag}`;
}
