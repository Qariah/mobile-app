#!/usr/bin/env node
// @ai
//
// scripts/__tests__/owner-replies.test.mjs
// ----------------------------------------
// Pure-function tests for scripts/lib/owner-replies.mjs, and for the reply
// effects in docs/operations/owner-actions.json.
//
// Run:  node --test scripts/__tests__/owner-replies.test.mjs

import {describe, it} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {
  EFFECT_FIELDS,
  applyOwnerReplies,
  matchPhrase,
  ownerOf,
  parseOwnerReplies,
  replyLine,
} from '../lib/owner-replies.mjs';
import {loadOwnerActionsWithReplies} from '../lib/owner-actions-facts.mjs';
import {CHECKS} from '../lib/owner-actions.mjs';

const LIST = JSON.parse(
  readFileSync(
    new URL('../../docs/operations/owner-actions.json', import.meta.url),
    'utf8',
  ),
);
// The tests apply the phase 2 replies, so they need the item unanswered; the
// live file records the real answer.
Object.assign(
  LIST.items.find(i => i.id === 'phase2-decision'),
  {
    status: null,
    statusDate: null,
    answer: null,
  },
);

const comment = (body, at = '2026-10-11T15:53:41Z', login = 'omar-zarka') => ({
  body,
  created_at: at,
  html_url: `https://github.com/omar-zarka/qariah-v2/issues/510#c-${at}`,
  user: {login},
});

describe('parseOwnerReplies', () => {
  const owner = 'omar-zarka';
  it('keeps only owner comments that start with owner-reply:', () => {
    const rs = parseOwnerReplies(
      [
        comment('owner-reply: share fixed'),
        comment('OWNER-REPLY:   play fixed  ', '2026-10-10T09:00:00Z'),
        comment('share fixed'), // no prefix
        comment('owner-reply: billing fixed', undefined, 'someone-else'),
        comment('<!-- daily-card date=2026-10-11 -->\nowner-reply: x'),
        comment('owner-reply:'), // empty
      ],
      {owner},
    );
    assert.deepEqual(
      rs.map(r => [r.date, r.text]),
      [
        ['2026-10-10', 'play fixed'],
        ['2026-10-11', 'share fixed'],
      ],
    );
  });
  it('drops the footer that the cloud GitHub proxy appends', () => {
    const [r] = parseOwnerReplies(
      [
        comment(
          'owner-reply: Mac checks are off on purpose\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_',
        ),
      ],
      {owner},
    );
    assert.equal(r.text, 'Mac checks are off on purpose');
  });
  it('matches the owner login in any case, and needs an owner', () => {
    assert.equal(
      parseOwnerReplies([comment('owner-reply: a', undefined, 'Omar-Zarka')], {
        owner,
      }).length,
      1,
    );
    assert.equal(
      parseOwnerReplies([comment('owner-reply: a')], {owner: ''}).length,
      0,
    );
  });
  it('reads the owner from the repository name', () => {
    assert.equal(ownerOf('omar-zarka/qariah-v2'), 'omar-zarka');
  });
});

describe('matchPhrase', () => {
  const replies = LIST.replies;
  it('matches a phrase, with quotes, case and extra words', () => {
    assert.equal(
      matchPhrase('play fixed', replies).item,
      'play-vitals-permission',
    );
    assert.equal(matchPhrase("'Phase 2 YES'", replies).answer, undefined);
    assert.equal(matchPhrase("'Phase 2 YES'", replies).phrase, 'phase 2 yes');
    assert.equal(
      matchPhrase('phase 2 no, keep the Mac for fixes', replies).phrase,
      'phase 2 no',
    );
  });
  it('needs the phrase to end at a word boundary', () => {
    assert.equal(matchPhrase('phase 2 yesterday', replies), null);
    assert.equal(matchPhrase('the play fixed it', replies), null);
  });
  it('reads only the first line', () => {
    assert.equal(matchPhrase('thanks\nplay fixed', replies), null);
  });
});

describe('applyOwnerReplies', () => {
  const at = (text, date) => ({text, date, at: `${date}T12:00:00Z`});
  it('applies an effect with the reply date, and never edits the input', () => {
    const before = JSON.stringify(LIST);
    const {list, applied} = applyOwnerReplies(LIST, [
      at('phase 2 yes', '2026-10-17'),
    ]);
    const item = list.items.find(i => i.id === 'phase2-decision');
    assert.equal(item.status, 'done');
    assert.equal(item.answer, 'yes');
    assert.equal(item.statusDate, '2026-10-17');
    assert.deepEqual(applied, [
      {phrase: 'phase 2 yes', item: 'phase2-decision', date: '2026-10-17'},
    ]);
    assert.equal(JSON.stringify(LIST), before);
  });
  it('lets a newer reply win', () => {
    const {list} = applyOwnerReplies(LIST, [
      at('phase 2 yes', '2026-10-17'),
      at('phase 2 no', '2026-10-18'),
    ]);
    assert.equal(list.items.find(i => i.id === 'phase2-decision').answer, 'no');
  });
  it('skips a phrase with no effect, a closed item, and an older reply', () => {
    const closed = JSON.parse(JSON.stringify(LIST));
    closed.items.find(i => i.id === 'github-billing').closedOn = '2026-10-01';
    closed.items.find(i => i.id === 'play-vitals-permission').statusDate =
      '2026-10-20';
    const {applied} = applyOwnerReplies(closed, [
      at('merge 502', '2026-10-11'),
      at('billing fixed', '2026-10-11'),
      at('play fixed', '2026-10-11'),
    ]);
    assert.deepEqual(applied, []);
  });
  it('a reply makes the play item wait instead of asking', () => {
    // A cloud card whose Play line is an error (the 2026-09-27 shape).
    const card = {
      body: [
        '<!-- daily-card date=2026-10-11 sections=triage host=cloud -->',
        '```text',
        'ANDROID · v2 only  day     7d    28d',
        'Play · seen      error: The caller does not ',
        '```',
      ].join('\n'),
      createdAt: '2026-10-11T20:12:00Z',
    };
    const decide = l => {
      const item = l.items.find(i => i.id === 'play-vitals-permission');
      return CHECKS[item.check].decide(
        item,
        {cardComments: [card]},
        {today: '2026-10-11'},
      ).state;
    };
    assert.equal(decide(LIST), 'needs-you');
    const {list} = applyOwnerReplies(LIST, [at('play fixed', '2026-10-11')]);
    assert.equal(decide(list), 'waiting');
  });
});

describe('owner-actions.json reply effects', () => {
  it('sets only the hand-written fields', () => {
    for (const r of LIST.replies)
      for (const k of Object.keys(r.effect || {}))
        assert.ok(EFFECT_FIELDS.includes(k), `${r.phrase}: ${k}`);
  });
});

describe('replyLine', () => {
  it('says whether a phrase applies or needs a session', () => {
    const r = {date: '2026-10-11', text: 'merge 502'};
    assert.match(replyLine(r, LIST.replies), /a session must act/);
    assert.match(
      replyLine({...r, text: 'play fixed'}, LIST.replies),
      /play-vitals-permission: applied/,
    );
    assert.equal(
      replyLine({...r, text: 'local triage disabled'}, LIST.replies),
      '2026-10-11 · local triage disabled',
    );
  });
});

describe('loadOwnerActionsWithReplies', () => {
  it('applies the replies that the reader gives', () => {
    const {list, applied} = loadOwnerActionsWithReplies({
      read: () => ({replies: [{text: 'billing fixed', date: '2026-10-11'}]}),
    });
    assert.equal(
      list.items.find(i => i.id === 'github-billing').status,
      'done',
    );
    assert.equal(applied.length, 1);
  });
  it('keeps the file and reports the error when the read fails', () => {
    const r = loadOwnerActionsWithReplies({
      read: () => {
        throw new Error('HTTP 502');
      },
    });
    assert.ok(r.list.items.length);
    assert.equal(r.repliesError, 'HTTP 502');
  });
});
