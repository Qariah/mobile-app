import {test} from 'node:test';
import assert from 'node:assert/strict';
import {draftTextOf, hasLink} from '../lib/reply-draft-text.mjs';

const REPLY =
  'Thank you for listening, and for telling us. We have fixed it.';

test('strips the marker, the header and the tooling footer', () => {
  const body = `<!-- reply-draft -->\n**Reply draft** — app-store, 62/5970 chars. Edit this comment.\n\n${REPLY}\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n`;
  assert.equal(draftTextOf(body), REPLY);
  assert.equal(hasLink(draftTextOf(body)), false);
});

test('a draft with no footer is unchanged', () => {
  const body = `<!-- reply-draft -->\n**Reply draft** — play-store, 62/350 chars.\n\n${REPLY}`;
  assert.equal(draftTextOf(body), REPLY);
});

test('a horizontal rule inside the reply stays', () => {
  const inner = `${REPLY}\n---\nSecond part.`;
  const body = `<!-- reply-draft -->\n**Reply draft** — app-store.\n\n${inner}`;
  assert.equal(draftTextOf(body), inner);
});

test('hasLink finds a link that is left in the text', () => {
  assert.equal(hasLink('see https://example.com'), true);
  assert.equal(hasLink(REPLY), false);
});
