// @ai
import assert from 'node:assert/strict';
import {test} from 'node:test';
import {
  candidates,
  evaluate,
  isApprovalText,
  nextApproved,
  parseEvents,
  verifyFile,
  whatToTest,
} from '../lib/promotion-approval.mjs';

const SHA = 'a'.repeat(40);
const NOW = Date.parse('2026-11-10T12:00:00Z');
let id = 0;
const c = (at, body, extra = {}) => ({
  id: ++id,
  user: {login: 'omar-zarka'},
  created_at: at,
  updated_at: at,
  html_url: `u/${id}`,
  body,
  ...extra,
});
const READY = c(
  '2026-11-09T01:00:00Z',
  `release-audit: READY public-beta 3790 commit=${SHA}\n\ndetail`,
);
const GO = c('2026-11-09T02:00:00Z', 'owner-reply: go public-beta 3790');
const events = list => parseEvents(list, {owner: 'omar-zarka'});
const state = list =>
  evaluate(events(list), {action: 'public-beta', build: 3790, now: NOW}).state;

test('a reply after READY approves the build', () => {
  assert.equal(state([READY, GO]), 'approved');
  assert.equal(
    nextApproved(events([READY, GO]), {action: 'public-beta', now: NOW}).build,
    '3790',
  );
});

test('no READY line, no approval', () => {
  assert.equal(state([GO]), 'no-ready');
});

test('a reply before READY does not count', () => {
  const early = c('2026-11-08T01:00:00Z', 'owner-reply: go public-beta 3790');
  assert.equal(state([early, READY]), 'no-approval');
});

test('another build or another action does not count', () => {
  assert.equal(
    state([
      READY,
      c('2026-11-09T02:00:00Z', 'owner-reply: go public-beta 3791'),
    ]),
    'no-approval',
  );
  assert.equal(
    state([READY, c('2026-11-09T02:00:00Z', 'owner-reply: go prod 3790')]),
    'no-approval',
  );
});

test('a comment by another login does not count', () => {
  const other = c('2026-11-09T02:00:00Z', 'owner-reply: go public-beta 3790', {
    user: {login: 'mallory'},
  });
  assert.equal(state([READY, other]), 'no-approval');
  const fakeReady = c(
    '2026-11-09T01:00:00Z',
    `release-audit: READY public-beta 3790 commit=${SHA}`,
    {user: {login: 'mallory'}},
  );
  assert.equal(state([fakeReady, GO]), 'no-ready');
});

test('the comment must be exactly the approval', () => {
  for (const body of [
    'owner-reply: go public-beta 3790 please',
    'owner-reply: go public-beta 3790\n\n---\n_Generated by Claude Code_',
    'owner-reply: go public-beta',
    'go public-beta 3790',
    'I said owner-reply: go public-beta 3790',
    'owner-reply: go public-beta 3790\nrelease-audit: READY public-beta 3790',
  ]) {
    assert.equal(
      state([READY, c('2026-11-09T02:00:00Z', body)]),
      'no-approval',
      body,
    );
  }
});

test('a near miss is reported as ignored', () => {
  const ev = events([
    c('2026-11-09T02:00:00Z', 'owner-reply: go public-beta 3790 please'),
  ]);
  assert.equal(ev[0].kind, 'ignored');
});

test('an edited comment does not count', () => {
  const edited = c('2026-11-09T02:00:00Z', 'owner-reply: go public-beta 3790', {
    updated_at: '2026-11-09T03:00:00Z',
  });
  assert.equal(state([READY, edited]), 'no-approval');
});

test('the approval expires after 7 days', () => {
  const old = evaluate(events([READY, GO]), {
    action: 'public-beta',
    build: 3790,
    now: Date.parse('2026-11-16T03:00:00Z'),
  });
  assert.equal(old.state, 'expired');
});

test('NOT READY after READY voids it; a later READY and reply restore it', () => {
  const no = c(
    '2026-11-09T01:30:00Z',
    'release-audit: NOT READY public-beta 3790',
  );
  assert.equal(state([READY, no, GO]), 'voided');
  const ready2 = c(
    '2026-11-09T03:00:00Z',
    `release-audit: READY public-beta 3790 commit=${SHA}`,
  );
  assert.equal(state([READY, no, GO, ready2]), 'no-approval');
  const go2 = c('2026-11-09T04:00:00Z', 'owner-reply: go public-beta 3790');
  assert.equal(state([READY, no, GO, ready2, go2]), 'approved');
});

test('a cancel after the reply stops it; a later reply restores it', () => {
  const cancel = c('2026-11-09T03:00:00Z', 'owner-reply: cancel 3790');
  assert.equal(state([READY, GO, cancel]), 'cancelled');
  const go2 = c('2026-11-09T04:00:00Z', 'owner-reply: go public-beta 3790');
  assert.equal(state([READY, GO, cancel, go2]), 'approved');
});

test('a cancel counts in every natural form, and after an edit', () => {
  const at = '2026-11-09T03:00:00Z';
  for (const [body, extra] of [
    ['owner-reply: cancel public-beta 3790', {}],
    ['owner-reply: cancel 3790 please', {}],
    ['owner-reply: stop 3790', {}],
    ['owner-reply: hold 3790', {}],
    ['owner-reply: cancel', {}],
    ['owner-reply: Cancel 3790', {}],
    ['owner-reply: cancel 3790', {updated_at: '2026-11-09T03:10:00Z'}],
  ]) {
    assert.equal(state([READY, GO, c(at, body, extra)]), 'cancelled', body);
  }
  assert.equal(
    state([READY, GO, c(at, 'owner-reply: cancel 3791')]),
    'approved',
  );
});

test('a build that is out, or a newer build that is out, is not published again', () => {
  const done = c('2026-11-09T05:00:00Z', 'promotion: DONE public-beta 3790');
  const late = c('2026-11-09T06:00:00Z', 'owner-reply: go public-beta 3790');
  assert.equal(state([READY, GO, done, late]), 'done');
  const r2 = c(
    '2026-11-09T01:30:00Z',
    `release-audit: READY public-beta 3800 commit=${SHA}`,
  );
  const newer = c('2026-11-09T05:00:00Z', 'promotion: DONE public-beta 3800');
  assert.equal(state([READY, r2, GO, newer]), 'superseded');
  const older = c('2026-11-09T05:00:00Z', 'promotion: DONE public-beta 3780');
  assert.equal(state([READY, GO, older]), 'approved');
});

test('a run that died shows as stale, and the guard refuses it', () => {
  const start = c(
    '2026-11-09T03:00:00Z',
    'promotion: STARTED public-beta 3790',
  );
  const later = Date.parse('2026-11-09T09:30:00Z');
  const ev = events([READY, GO, start]);
  assert.equal(
    evaluate(ev, {action: 'public-beta', build: 3790, now: later}).state,
    'stale',
  );
  const file = {
    action: 'public-beta',
    build: '3790',
    sha: SHA,
    approvalId: GO.id,
    startedId: start.id,
  };
  assert.equal(verifyFile(file, ev, {now: later}).ok, false);
});

test('the What to Test text stops before the approval block', () => {
  const body =
    'release-audit: READY x\n\n| a |\n\n### What to Test\n\nPlay a surah.\nTell us.\n\n---\n\n**To publish, add this exact comment**';
  assert.equal(whatToTest(body), 'Play a surah.\nTell us.');
  assert.equal(whatToTest('no section'), '');
});

test('one reply gives one publish', () => {
  const start = c(
    '2026-11-10T09:00:00Z',
    'promotion: STARTED public-beta 3790',
  );
  const done = c('2026-11-10T10:00:00Z', 'promotion: DONE public-beta 3790');
  const failed = c(
    '2026-11-10T10:00:00Z',
    'promotion: FAILED public-beta 3790 ios',
  );
  assert.equal(state([READY, GO, start]), 'in-progress');
  assert.equal(state([READY, GO, start, done]), 'done');
  assert.equal(state([READY, GO, start, failed]), 'failed');
  assert.equal(
    nextApproved(events([READY, GO, start]), {action: 'public-beta', now: NOW}),
    null,
  );
  const go2 = c('2026-11-10T11:00:00Z', 'owner-reply: go public-beta 3790');
  assert.equal(state([READY, GO, start, failed, go2]), 'approved');
});

test('a STARTED line carries the commit', () => {
  const start = c(
    '2026-11-09T03:00:00Z',
    `promotion: STARTED public-beta 3790 commit=${SHA}`,
  );
  assert.equal(events([start])[0].sha, SHA);
});

test('candidates lists the newest READY first', () => {
  const r2 = c(
    '2026-11-09T07:00:00Z',
    `release-audit: READY public-beta 3800 commit=${SHA}`,
  );
  const list = candidates(events([READY, GO, r2]), {now: NOW});
  assert.deepEqual(
    list.map(x => [x.build, x.state]),
    [
      ['3800', 'no-approval'],
      ['3790', 'approved'],
    ],
  );
});

test('the guard needs the file to match the started publish on GitHub', () => {
  const start = c(
    '2026-11-10T09:00:00Z',
    'promotion: STARTED public-beta 3790',
  );
  const ev = events([READY, GO, start]);
  const good = {
    action: 'public-beta',
    build: '3790',
    sha: SHA,
    approvalId: GO.id,
    startedId: start.id,
  };
  assert.equal(verifyFile(good, ev, {now: NOW}).ok, true);
  assert.equal(verifyFile(good, ev, {now: NOW}).sha, SHA);
  assert.equal(verifyFile(null, ev, {now: NOW}).ok, false);
  assert.equal(
    verifyFile({...good, sha: 'b'.repeat(40)}, ev, {now: NOW}).ok,
    false,
  );
  assert.equal(verifyFile({...good, approvalId: 1}, ev, {now: NOW}).ok, false);
  assert.equal(verifyFile({...good, startedId: 1}, ev, {now: NOW}).ok, false);
  assert.equal(verifyFile({...good, build: '3791'}, ev, {now: NOW}).ok, false);
  // Not started: approved is not enough for the guard.
  assert.equal(verifyFile(good, events([READY, GO]), {now: NOW}).ok, false);
  // Finished: the file is dead.
  const done = c('2026-11-10T10:00:00Z', 'promotion: DONE public-beta 3790');
  assert.equal(
    verifyFile(good, events([READY, GO, start, done]), {now: NOW}).ok,
    false,
  );
});

test('isApprovalText finds the forms that post must refuse', () => {
  for (const t of [
    'go prod 3790',
    'owner-reply: go public-beta 3790',
    'Go Prod 1',
    'go public-beta',
  ]) {
    assert.equal(isApprovalText(t), true, t);
  }
  for (const t of ['share fixed', 'go ahead', 'cancel 3790', 'phase 2 yes']) {
    assert.equal(isApprovalText(t), false, t);
  }
});
