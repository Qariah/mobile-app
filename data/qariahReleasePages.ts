/** The release that the pages announce. */
export const QARIAH_RELEASE_PAGES_VERSION = '3.2.3';

/**
 * `true` when `version` is `QARIAH_RELEASE_PAGES_VERSION` or newer. A version
 * that cannot be read gives `false`: no page, never a wrong one.
 */
export function isReleasePagesVersion(version: string): boolean {
  const current = semver.coerce(version);
  const release = semver.coerce(QARIAH_RELEASE_PAGES_VERSION);
  return current !== null && release !== null && semver.gte(current, release);
}

